std::string methodIdentifier(const std::string& protoName) {
  if (cppKeywords().count(protoName) || reservedMembers().count(protoName)) return protoName + "_";
  return protoName;
}

std::string packageNamespace(const std::string& package) {
  std::string out;
  for (char c : package) {
    if (c == '.') {
      out += "::";
    } else {
      out.push_back(c);
    }
  }
  return out;
}

bool ProtobusGenerator::Generate(const gpb::FileDescriptor* file, const std::string&,
                                 gpb::compiler::GeneratorContext* context, std::string* error) const {
  const std::string base = stripProto(std::string(file->name()));
  {
    std::unique_ptr<gpb::io::ZeroCopyOutputStream> out(context->Open(base + ".protobus.h"));
    gpb::io::Printer printer(out.get(), '$');
    generateHeader(file, printer);
    if (printer.failed()) {
      *error = "failed writing " + base + ".protobus.h";
      return false;
    }
  }
  {
    std::unique_ptr<gpb::io::ZeroCopyOutputStream> out(context->Open(base + ".protobus.cc"));
    gpb::io::Printer printer(out.get(), '$');
    generateSource(file, printer);
    if (printer.failed()) {
      *error = "failed writing " + base + ".protobus.cc";
      return false;
    }
  }
  return true;
}

